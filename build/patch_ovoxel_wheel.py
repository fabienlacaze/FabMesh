"""Remove the nvdiffrast (NVIDIA non-commercial) import from the o_voxel wheel.

WHY -- SALE BLOCKER
-------------------
`build/wheels/o_voxel-0.0.1-cp311-cp311-win_amd64.whl` is bundled in the sold
package (package.json extraResources: build/wheels -> resources/wheels) and is
pip-installed on the customer machine by scripts/wizard_install_deps.py.

The upstream wheel carries, in `o_voxel/postprocess.py`:

    import nvdiffrast.torch as dr

nvdiffrast is under the NVIDIA Source Code License -- **non-commercial**, so
that statement must not be distributed in a paid product. And because
`o_voxel/__init__.py` eagerly does `from . import (..., postprocess, ...)`,
ANY `import o_voxel` executes it. scripts/local_trellis2_bridge.py and
scripts/trellis2_native_full_pipeline.py both import o_voxel.

Two consequences on a customer machine, not just one:
  1. licensing: the NC import statement ships;
  2. functional: the wizard never installs nvdiffrast, so `import o_voxel`
     raises ModuleNotFoundError -- the default mesh engine cannot start.

scripts/install_kaolin_shim.py already fixes the *dev venv* copy, but it
patches a hard-coded `external/TRELLIS2_win/.venv/...` path, which does not
exist on a customer machine. Patching the wheel is the only fix that reaches
paying customers.

WHAT THIS DOES
--------------
Rewrites the wheel in place:
  * adds `o_voxel/_kaolin_compat.py` -- a self-contained copy of
    scripts/trellis2_kaolin_shim.py (kaolin, Apache-2.0). Self-contained
    matters: the dev patch imports `trellis2.renderers`, which is not on the
    path when o_voxel is imported standalone.
  * rewrites the import in `o_voxel/postprocess.py` to `from . import
    _kaolin_compat as dr`. postprocess.py only ever calls
    RasterizeCudaContext / rasterize / interpolate, which the shim provides.
  * regenerates dist-info/RECORD (sha256 + size) so pip's install-time
    integrity check still passes.

Idempotent, and safe to run when the wheel is missing (prints a warning and
exits 0 -- a dev tree without build/wheels is a valid state).

Usage:
    python build/patch_ovoxel_wheel.py            # patch if needed
    python build/patch_ovoxel_wheel.py --verify   # exit 1 if not patched
"""
import argparse
import base64
import hashlib
import os
import pathlib
import shutil
import sys
import tempfile
import zipfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
WHEEL = ROOT / 'build' / 'wheels' / 'o_voxel-0.0.1-cp311-cp311-win_amd64.whl'
SHIM_SRC = ROOT / 'scripts' / 'trellis2_kaolin_shim.py'

TARGET_PY = 'o_voxel/postprocess.py'
SHIM_DST = 'o_voxel/_kaolin_compat.py'
RECORD = 'o_voxel-0.0.1.dist-info/RECORD'

ORIGINAL_IMPORT = 'import nvdiffrast.torch as dr'
PATCHED_IMPORT = (
    '# FabMesh commercial build: nvdiffrast (NVIDIA Source Code License,\n'
    '# non-commercial) replaced by a kaolin-backed shim (Apache-2.0).\n'
    '# See build/patch_ovoxel_wheel.py.\n'
    'from . import _kaolin_compat as dr'
)

# Prepended to the shim copy so that `import o_voxel` never hard-requires
# kaolin at import time -- o_voxel/__init__.py imports postprocess eagerly,
# but to_glb() may never be called. The upstream file imports kaolin at
# module level; we defer it into the functions instead.
LAZY_HEADER = '''# ---------------------------------------------------------------------------
# GENERATED by build/patch_ovoxel_wheel.py from scripts/trellis2_kaolin_shim.py
# Do not edit here -- edit the canonical shim and re-run the patcher.
#
# Difference vs the canonical shim: kaolin is imported lazily (inside
# rasterize()) instead of at module level, because o_voxel/__init__.py
# imports postprocess.py eagerly and we must not make `import o_voxel` fail
# on a machine where kaolin is not installed yet.
# ---------------------------------------------------------------------------
'''


def _sha256_b64(data: bytes) -> str:
    d = hashlib.sha256(data).digest()
    return base64.urlsafe_b64encode(d).rstrip(b'=').decode('ascii')


def _make_shim_source() -> str:
    """Canonical shim, with the module-level kaolin import made lazy."""
    src = SHIM_SRC.read_text(encoding='utf-8')
    module_import = 'from kaolin.render.mesh import rasterize as _kaolin_rasterize'
    if module_import not in src:
        raise SystemExit(
            f'ERROR: expected kaolin import not found in {SHIM_SRC}.\n'
            'The canonical shim changed -- update build/patch_ovoxel_wheel.py.')
    src = src.replace(module_import, '''_kaolin_rasterize = None


def _load_kaolin():
    """Import kaolin on first use (see header)."""
    global _kaolin_rasterize
    if _kaolin_rasterize is None:
        from kaolin.render.mesh import rasterize as _r
        _kaolin_rasterize = _r
    return _kaolin_rasterize''')
    # rasterize() is the only entry point that touches kaolin.
    src = src.replace('    interp, face_idx = _kaolin_rasterize(',
                      '    interp, face_idx = _load_kaolin()(')
    if '_load_kaolin()(' not in src:
        raise SystemExit(
            'ERROR: could not rewrite the _kaolin_rasterize call site.\n'
            'The canonical shim changed -- update build/patch_ovoxel_wheel.py.')
    return LAZY_HEADER + src


def is_patched(wheel: pathlib.Path) -> bool:
    with zipfile.ZipFile(wheel) as z:
        names = z.namelist()
        if SHIM_DST not in names:
            return False
        src = z.read(TARGET_PY).decode('utf-8')
    return ORIGINAL_IMPORT not in src and 'from . import _kaolin_compat as dr' in src


def patch(wheel: pathlib.Path) -> None:
    shim_source = _make_shim_source()

    with zipfile.ZipFile(wheel) as z:
        entries = [(i, z.read(i.filename)) for i in z.infolist()]

    post = None
    for info, data in entries:
        if info.filename == TARGET_PY:
            post = data.decode('utf-8')
    if post is None:
        raise SystemExit(f'ERROR: {TARGET_PY} not found in {wheel.name}')
    if ORIGINAL_IMPORT not in post:
        raise SystemExit(
            f'ERROR: "{ORIGINAL_IMPORT}" not found in {TARGET_PY}.\n'
            'The upstream wheel changed -- re-check it by hand before shipping.')
    patched_post = post.replace(ORIGINAL_IMPORT, PATCHED_IMPORT)

    new_files = {
        TARGET_PY: patched_post.encode('utf-8'),
        SHIM_DST: shim_source.encode('utf-8'),
    }

    # RECORD must list every file with its new hash/size or pip refuses the
    # install (and `pip check`/wheel unpacking reports a corrupt archive).
    record_lines = []
    for info, data in entries:
        if info.filename == RECORD:
            continue
        payload = new_files.get(info.filename, data)
        record_lines.append(
            f'{info.filename},sha256={_sha256_b64(payload)},{len(payload)}')
    record_lines.append(
        f'{SHIM_DST},sha256={_sha256_b64(new_files[SHIM_DST])},'
        f'{len(new_files[SHIM_DST])}')
    record_lines.append(f'{RECORD},,')          # RECORD itself: no hash
    record_data = ('\n'.join(sorted(set(record_lines))) + '\n').encode('utf-8')

    tmp_fd, tmp_path = tempfile.mkstemp(suffix='.whl', dir=str(wheel.parent))
    os.close(tmp_fd)
    try:
        with zipfile.ZipFile(tmp_path, 'w', zipfile.ZIP_DEFLATED) as out:
            written = set()
            for info, data in entries:
                if info.filename == RECORD:
                    continue
                out.writestr(info, new_files.get(info.filename, data))
                written.add(info.filename)
            if SHIM_DST not in written:
                out.writestr(SHIM_DST, new_files[SHIM_DST])
            out.writestr(RECORD, record_data)
        shutil.move(tmp_path, str(wheel))
    finally:
        if os.path.exists(tmp_path):
            os.remove(tmp_path)

    print(f'[patch_ovoxel_wheel] patched: {wheel.name}')
    print(f'[patch_ovoxel_wheel]   {TARGET_PY}: nvdiffrast -> _kaolin_compat')
    print(f'[patch_ovoxel_wheel]   added {SHIM_DST} ({len(new_files[SHIM_DST])} B)')
    print(f'[patch_ovoxel_wheel]   RECORD regenerated ({len(record_lines)} entries)')


def _run(verify: bool) -> int:
    if not WHEEL.is_file():
        msg = f'{WHEEL} not found (run build/fetch_trellis2_wheels.py first)'
        if verify:
            print(f'[patch_ovoxel_wheel] SKIP: {msg}')
            return 0
        print(f'[patch_ovoxel_wheel] WARNING: {msg}')
        return 0

    if is_patched(WHEEL):
        print(f'[patch_ovoxel_wheel] already patched: {WHEEL.name}')
        return 0
    if verify:
        print(f'[patch_ovoxel_wheel] FAIL: {WHEEL.name} still imports '
              f'nvdiffrast (NVIDIA non-commercial) -- run '
              f'`python build/patch_ovoxel_wheel.py` before packaging.')
        return 1

    patch(WHEEL)
    return 0


def main_no_args() -> int:
    """Programmatic entry point (build/fetch_trellis2_wheels.py), no argparse."""
    return _run(verify=False)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument('--verify', action='store_true',
                    help='do not modify anything; exit 1 if the wheel still '
                         'carries the nvdiffrast import')
    args = ap.parse_args()
    return _run(verify=args.verify)


if __name__ == '__main__':
    sys.exit(main())
